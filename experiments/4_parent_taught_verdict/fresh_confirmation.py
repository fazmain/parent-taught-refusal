    ap.add_argument("--smoke", action="store_true", help=f"{SMOKE_PER_POOL} sentences per pool. NOT a result")
    ap.add_argument("--self-test", action="store_true")
    ap.add_argument("--self-check-cpu", default=None, metavar="OUT")
