def check_rows(rows: list[dict], items: list[dict], offsets: dict, pairs=None, verdict=None) -> None:
    """Every (model, offset) has exactly one row per (sentence, frame) job, matching the sentence's pool / id /
    label / hash / scene; no row carries text; the stored verdict is the parse of its ids; invalid <=> class
    invalid; a verdict row carries three text tokens and the offset it was generated at. `pairs` (the (model,
    offset) pairs, default round 4's) and `verdict` (the predicate saying which models emit a verdict) are round 5's
    hooks."""
    want = {(it["idx"], init): it for it, init in jobs_of(items)}
    n_text_verdict = len(VERDICT_IDS_REF[STOP])
    is_v = verdict or is_verdict
    bad = []
    extra_text = {}     # (model, offset) -> rows whose valid verdict is followed by more text tokens (reported, not fatal:
                        # the behaviour class comes from the action ids; the round-4 run saw I2 double its verdict on 1 fresh row)
    for r in rows:
        if set(r) != set(ROW_KEYS):
            bad.append(f"row keys {sorted(set(r) ^ set(ROW_KEYS))}")
            break
    for src, offset in (pairs or models_of()):
        mr = [r for r in rows if r["model"] == src and r["offset"] == offset]
        keys = [(r["idx"], r["init"]) for r in mr]
        if len(keys) != len(set(keys)) or set(keys) != set(want):
            bad.append(f"{key_of(src, offset)}: {len(keys)} rows ({len(set(keys))} distinct) for {len(want)} jobs")
            continue
        b = b_of(offsets, src, offset)
        for r in mr:
            it = want[(r["idx"], r["init"])]
            if (r["pool"], r["id"], r["harm"], r["text_sha1"], r["task_id"], r["frame"]) !=\
                    (it["pool"], it["id"], it["harm"], it["text_sha1"], it["task_id"],
                     f"t{it['task_id']}_i{r['init']}.png"):
                bad.append(f"{key_of(src, offset)}: row {r['pool']}/{r['idx']}/i{r['init']} does not match its "
                           f"sentence")
                break
            if (b is None) != (r["b"] is None) or (b is not None and abs(float(r["b"]) - b) > D_TOL):
                bad.append(f"{key_of(src, offset)}: row b {r['b']}, offset b {b}")
                break
            if is_v(src) and r["verdict"] != "none" and r["n_text"] != n_text_verdict:
                if r["n_text"] < n_text_verdict:
                    bad.append(f"{key_of(src, offset)}: a verdict row carries {r['n_text']} text tokens, fewer than "
                               f"{n_text_verdict}")
                    break
                extra_text.setdefault(key_of(src, offset), []).append(f"{r['pool']}/{r['idx']}/i{r['init']}:{r['n_text']}")
    for r in rows:
        if parse_verdict(r["gen_ids"], VERDICT_IDS_REF) != r["verdict"]:
            bad.append(f"{r['model']}: stored verdict {r['verdict']} is not the parse of its ids")
            break
        if (r["cls"] == "invalid") != bool(r["invalid"]) or r["cls"] not in CLASSES:
            bad.append(f"{r['model']}: class {r['cls']} vs invalid flag {r['invalid']}")
            break
    if bad:
        raise SystemExit("fresh rows fail the consistency check: " + "; ".join(bad))
    for key, rows_ in extra_text.items():
        print(f"[check] {key}: {len(rows_)} verdict row(s) with extra text tokens after a valid verdict (pool/idx/init:"
              f"n_text) {rows_[:6]}; behaviour class taken from the action ids as for every row", flush=True)


def finish(a, items: list[dict], offsets: dict, stop_go, steps: int, calib_sha: str,
           append_results: bool) -> int:
    P = paths(a.out)
    rows = read_jsonl(P["rows"])
    check_rows(rows, items, offsets)
    summ = summarize(rows, offsets, stop_go)
    lines = table_lines(summ, offsets, a.smoke)
    Report()("\n".join(lines))
    elig = eligible_of(summ)
    stamp = time.strftime("%Y-%m-%d %H:%M:%S")
    gates = {}
    for src in elig:
        gates[src] = str(write_gate(a, src, offsets, summ, steps, calib_sha))
    go = {"exp": EXP, "ts": stamp, "smoke": bool(a.smoke), "pass": {s: int(summ[key_of(s, RULE_OFFSET)]["eligible"])
                                                                    for s in PRIORITY},
          "eligible": elig, "pick": (elig[0] if elig else None),
          "arm": (arm_name(elig[0]) if elig else None),
          "gate_file": (gates[elig[0]] if elig else None), "gate_files": gates,
          "b": (float(offsets[elig[0]][RULE_OFFSET]) if elig else None), "quantile": OFFSET_Q[RULE_OFFSET],
          "priority": list(PRIORITY)}
    P["offsets"].write_text(json.dumps({"exp": EXP, "ts": stamp, "quantiles": OFFSET_Q, "check_quantile": CHECK_Q,
                                        "calib": str(a.calib), "calib_sha256": calib_sha, "offsets": offsets},
                                       indent=1, default=float))
    doc = {"exp": EXP, "ts": stamp, "smoke": bool(a.smoke), "confirm": CONFIRM, "confirm_sha256": CONFIRM_SHA256,
           "pools": list(POOLS), "n_items": len(items), "n_jobs": len(jobs_of(items)),
           "models": {key_of(s, o): {"source": s, "offset": o, "adapter": (None if s == BASE else
                                                                           SOURCES[s]["name"])}
                      for s, o in models_of()},
           "sources": {s: SOURCES[s] for s in SOURCES}, "offsets": offsets, "rules": list(FRESH_RULES),
           "rule_offset": RULE_OFFSET, "verdict_ids": VERDICT_IDS_REF, "steps": int(steps),
           "summary": summ, "go": go}
    P["summary"].write_text(json.dumps(doc, indent=1, default=float))
    P["table"].write_text("\n".join(lines) + "\n")
    P["go"].write_text(json.dumps(go, indent=1, default=float))
    if append_results and not a.smoke:
        with (RESULTS_DIR / "results.jsonl").open("a") as f:
            for key, s in summ.items():
                for pool, v in s["pools"].items():
                    f.write(json.dumps({"exp": EXP, "ts": stamp, "model": key, "source": s["source"],
                                        "offset": s["offset"], "offset_b": s["b"], "pool": pool, **v}) + "\n")
    print("wrote\n" + "\n".join(file_line(P[k]) for k in ("rows", "offsets", "calib", "summary", "table", "go"))
          + ("\n" + "\n".join(file_line(Path(p)) for p in gates.values()) if gates else ""), flush=True)
    return 0 if (elig or a.smoke) else NO_GO_EXIT


def load_inputs(a) -> tuple:
    items = build_items(a.confirm, Path(a.f1_data), a.smoke)
    calib_raw = Path(a.calib).read_bytes()
    calib_sha = hashlib.sha256(calib_raw).hexdigest()
    offsets = offsets_from_calib(json.loads(calib_raw.decode("utf-8")))
    steps = int(load_json(a.rows_summary)["steps_all_arms"])
    return items, offsets, calib_sha, steps


def stage_fresh(a) -> int:
    P = paths(a.out)
    rs = load_json(a.rows_summary)
    if rs["verdict_ids"] != VERDICT_IDS_REF:
        raise SystemExit(f"rows summary verdict ids {rs['verdict_ids']} != {VERDICT_IDS_REF}")
    stop_go = decision_ids(rs["verdict_ids"])
    adapters = {s: Path(a.adapters) / SOURCES[s]["name"] for s in SOURCES}
    missing = [str(p) for p in adapters.values() if not (p / "adapter_config.json").exists()]
    if missing:
        raise SystemExit(f"adapters missing: {missing}")
    if a.smoke:
        print(f"[smoke] {SMOKE_PER_POOL} sentences per pool, both frames. Smoke numbers are NOT results.", flush=True)
    items, offsets, calib_sha, steps = load_inputs(a)
    P["dir"].mkdir(parents=True, exist_ok=True)
    shutil.copy(a.calib, P["calib"])
    n_gen = len(jobs_of(items)) * (len(PRIORITY) * len(OFFSETS) + len(FREE_ORDER) + 1)
    print(f"[jobs] {len(items)} fresh sentences x {len(EVAL_INITS)} frames = {len(jobs_of(items))} generations per "
          f"(model, offset); {len(PRIORITY)} verdict installs x {len(OFFSETS)} offsets + {len(FREE_ORDER)} free arms "
          f"+ base = {n_gen} generations from {len(SOURCES) + 1} checkpoint loads; decision ids STOP {stop_go[0]} / "
          f"GO {stop_go[1]}", flush=True)
    for src in PRIORITY:
        o = offsets[src]
        print(f"[offset] {src}: b0 0.000, b95 {o['b95']:+.4f}, b97 {o['b97']:+.4f} (b90 recomputed "
              f"{o['b90_check']:+.4f} = the G16 record {o['b90_stored']:+.4f}, {o['n_b']} prefills)", flush=True)
    from single_model_judges import forbid_parent
    forbid_parent()
    rep = Report()

    def check_ids(policy):
        if decision_ids(verdict_token_ids(policy, rep)) != stop_go:
            raise SystemExit("the policy tokenizer's verdict ids differ from the rows stage")

    rdoc_path = {32: Path(a.restore32), 128: Path(a.restore128)}
    rdoc = {r: load_json(p) for r, p in rdoc_path.items()
            if any(SOURCES[s]["restore"] == r for s in SOURCES)}

    def factory(src):
        if src == BASE:
            from refusal.nora_policy import NoraPolicy
            return NoraPolicy(a.checkpoint, unnorm_key=a.suite, time_horizon=a.time_horizon)
        rc = SOURCES[src]
        ctx = {"steps": steps, "restore_doc": rdoc_path.get(rc["restore"]), "restore": rdoc.get(rc["restore"])}
        return load_arm(a, src, str(adapters[src]), ctx, rc=rc)

    run_fresh(a, items, offsets, factory, check_ids, stop_go)
    return finish(a, items, offsets, stop_go, steps, calib_sha, append_results=True)


