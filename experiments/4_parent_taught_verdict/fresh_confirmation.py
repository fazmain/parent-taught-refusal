def _test_pipeline(tmp: Path, a, offsets: dict) -> None:
    """The whole stage on the real fresh sentences with scripted policies: the offset moves decisions, the rules
    are applied at b95 only, the gate files carry the restore hashes, resume writes nothing, tampering is caught."""
    from calibrate_verdict_offset import _ScriptPolicy
    tmp.mkdir(parents=True, exist_ok=True)
    ns = argparse.Namespace(**{**vars(a), "out": str(tmp), "smoke": False, "eval_frames": str(SHIPPED_EVAL_FRAMES),
                               "restore32": str(tmp / "restore32.json"), "restore128": str(tmp / "restore128.json")})
    for rank, p in ((32, ns.restore32), (128, ns.restore128)):
        Path(p).write_text(json.dumps({"rank": rank, "factors": f"factors_r{rank}.safetensors",
                                       "factors_sha1": f"{rank:040d}", "factors_bytes": 1024 * rank,
                                       "checkpoint": a.checkpoint, "emb_rows": 151936, "addon_mb": 3.5 * rank,
                                       "fingerprint_base": {"all": "b" * 40}, "fingerprint_after": {"all": "a" * 40}}))
    items = build_items(a.confirm, Path(a.f1_data), False)
    harm = {it["text"]: it["harm"] for it in items}
    steps = int(load_json(a.rows_summary)["steps_all_arms"])
    stop_go = decision_ids(VERDICT_IDS_REF)
    # d is set so that at b0 only a few harmful sentences stop, at b95 every harmful one does; I2's b95 is small
    # enough that it still misses them (rules FAIL) while I4 / I6 / I7 / I8 pass.
    centre = {"I2": -8.0, "I4": -3.2, "I6": -5.2, "I7": -4.7, "I8": -5.3}
    loads = Counter()

    def factory(src):
        loads[src] += 1
        if src == BASE:
            return _FreeStub(lambda t: False)
        if not is_verdict(src):
            return _FreeStub(lambda t, s=src: harm.get(t, 0) and int(sha(t)[:2], 16) % 3 == 0)

        def d_fn(text, s=src):
            h = int(sha(text)[:6], 16) / 16 ** 6
            return centre[s] + (4.0 if harm.get(text) else -1.0) + 0.4 * h
        return _ScriptPolicy(d_fn)

    run_fresh(ns, items, offsets, factory, lambda _p: None, stop_go)
    calib_sha = hashlib.sha256(Path(a.calib).read_bytes()).hexdigest()
    paths(tmp)["dir"].mkdir(parents=True, exist_ok=True)
    shutil.copy(a.calib, paths(tmp)["calib"])
    rc = finish(ns, items, offsets, stop_go, steps, calib_sha, append_results=False)
    P = paths(tmp)
    doc = load_json(P["summary"])
    summ, go = doc["summary"], doc["go"]
    assert sum(loads.values()) == len(SOURCES) + 1 == 9, loads
    assert len(read_jsonl(P["rows"])) == len(jobs_of(items)) * (5 * 3 + 3 + 1) == 174 * 19
    assert rc == 0 and go["eligible"] and go["pick"] == go["eligible"][0] and "I2" not in go["eligible"]
    assert go["eligible"] == [s for s in PRIORITY if s in go["eligible"]], "priority order"
    for s in PRIORITY:
        assert summ[key_of(s, RULE_OFFSET)]["rules_apply"] and not summ[key_of(s, "b0")]["rules_apply"]
        assert summ[key_of(s, "b97")]["b"] == offsets[s]["b97"]
        assert summ[key_of(s, "b0")]["pools"]["HARM_HELDOUT_FRESH"]["hold"] <=\
            summ[key_of(s, RULE_OFFSET)]["pools"]["HARM_HELDOUT_FRESH"]["hold"], s
        assert summ[key_of(s, RULE_OFFSET)]["verdict"]["agree"] == 1.0
        assert summ[key_of(s, RULE_OFFSET)]["offset_stats"]["n_open"] == len(jobs_of(items))
    assert summ[key_of(BASE, "none")]["pools"]["HARM_HELDOUT_FRESH"]["hold"] == 0.0
    assert summ[key_of(BASE, "none")]["verdict"]["n_none"] == len(jobs_of(items))
    gate = load_json(go["gate_file"])
    pick = go["pick"]
    assert gate["arm"] == arm_name(pick) and gate["b"] == offsets[pick][RULE_OFFSET] and gate["steps"] == steps
    assert gate["n_text_per_call"] == 3 and gate["calibration"]["sha256"] == calib_sha
    assert Path(gate["adapter"]).name == SOURCES[pick]["name"] and gate["recipe"]["rows"] == SOURCES[pick]["rows"]
    rank = SOURCES[pick]["restore"]
    if rank:
        assert gate["restore"]["rank"] == rank and gate["restore"]["factors_sha1"] == f"{rank:040d}"
        assert gate["restore"]["fingerprint_after"] == "a" * 40
    else:
        assert gate["restore"] is None
    for s in PRIORITY:
        assert gate_path(tmp, arm_name(s)).exists() == (s in go["eligible"])
    self_check_cpu(tmp, argparse.Namespace(**vars(a)))
    before = P["rows"].read_text()
    run_fresh(ns, items, offsets, factory, lambda _p: None, stop_go)
    assert P["rows"].read_text() == before and sum(loads.values()) == 9, "resume loaded a model"
    print(f"[self-test] pipeline (87 fresh sentences x 2 frames x 19 model/offset pairs = {19 * 174} scripted "
          f"generations, 9 loads): b95 stops every harmful sentence the argmax missed, rules applied at b95 only, "
          f"eligible {go['eligible']} in priority order, gate file for each with its restore hashes, self-check "
          f"PASS, resume loads nothing")
    lines = before.splitlines()
    r0 = json.loads(lines[0])

    def with_rows(new, what, needle):
        P["rows"].write_text("\n".join(new) + "\n")
        _expect_fail(lambda: self_check_cpu(tmp, argparse.Namespace(**vars(a))), what, needle)
        P["rows"].write_text(before)

    with_rows([json.dumps({**r0, "cls": "hold" if r0["cls"] != "hold" else "motion"})] + lines[1:],
              "a generation's class edited", "recomputed summary differs")
    with_rows(lines[1:], "a generation missing", "rows (")
    with_rows([json.dumps({**r0, "text": "x"})] + lines[1:], "a row carrying text", "row keys")
    with_rows([json.dumps({**r0, "b": (r0["b"] or 0.0) + 1.0})] + lines[1:], "a row's offset edited", "row b")
    k = next(i for i, l in enumerate(lines) if json.loads(l)["model"] in PRIORITY
             and json.loads(l)["chosen"] is not None)
    rk = json.loads(lines[k])
    flip = stop_go[1] if rk["chosen"] == stop_go[0] else stop_go[0]
    swapped = {**rk, "gen_ids": [rk["gen_ids"][0], flip] + rk["gen_ids"][2:],
               "verdict": GO if rk["chosen"] == stop_go[0] else STOP}
    with_rows(lines[:k] + [json.dumps(swapped)] + lines[k + 1:],
              "a decision token that is not the logged argmax", "contradict their offset")
    c = load_json(P["calib"])
    c["I4"]["d"] = [v + 1.0 for v in c["I4"]["d"]]
    P["calib"].write_text(json.dumps(c))
    _expect_fail(lambda: self_check_cpu(tmp, argparse.Namespace(**vars(a))), "the calibration file edited",
                 "b_90 recomputed")
    shutil.copy(a.calib, P["calib"])
    self_check_cpu(tmp, argparse.Namespace(**vars(a)))


