def self_check_cpu(folder, a) -> None:
    """Recompute the offsets from the calibration file that travelled with the run, every row check, every per-pool
    rate, the rules, the verdict statistics, the GO map, the gate files and the table."""
    a.out = folder
    P = paths(folder)
    doc = load_json(P["summary"])
    a.smoke = bool(doc["smoke"])
    if P["calib"].exists():
        a.calib = str(P["calib"])
    items, offsets, calib_sha, steps = load_inputs(a)
    rows = read_jsonl(P["rows"])
    stop_go = decision_ids(doc["verdict_ids"])
    bad = []
    if json.dumps(offsets, sort_keys=True, default=float) != json.dumps(doc["offsets"], sort_keys=True, default=float):
        bad.append("the offsets recomputed from the calibration file differ from the stored ones")
    check_rows(rows, items, offsets)
    summ = summarize(rows, offsets, stop_go)
    if json.dumps(summ, default=float, sort_keys=True) != json.dumps(doc["summary"], default=float, sort_keys=True):
        diff = [k for k in summ if json.dumps(summ[k], default=float, sort_keys=True)
                != json.dumps(doc["summary"].get(k), default=float, sort_keys=True)]
        bad.append(f"recomputed summary differs for {diff}")
    elig = eligible_of(summ)
    go = load_json(P["go"])
    if go["eligible"] != elig or go["pick"] != (elig[0] if elig else None):
        bad.append(f"GO map recomputed {elig}; stored {go['eligible']} / {go['pick']}")
    for src in elig:
        p = gate_path(folder, arm_name(src))
        if not p.exists():
            bad.append(f"{p} is missing for the eligible model {src}")
            continue
        g = load_json(p)
        if abs(float(g["b"]) - float(offsets[src][RULE_OFFSET])) > 1e-9 or g["source"] != src:
            bad.append(f"{p}: b {g['b']} / source {g['source']} do not follow from the calibration")
        if (g["restore"] or {}).get("rank") != SOURCES[src]["restore"]:
            bad.append(f"{p}: restore rank {(g['restore'] or {}).get('rank')} != {SOURCES[src]['restore']}")
        if g["calibration"]["sha256"] != calib_sha and P["calib"].exists():
            bad.append(f"{p}: calibration sha256 does not match the file that travelled with the run")
    if P["table"].read_text() != "\n".join(table_lines(summ, offsets, a.smoke)) + "\n":
        bad.append("the table file differs from the table recomputed from the rows")
    print(f"[self-check] {folder}: {len(rows)} generations over {len(models_of())} (model, offset) pairs x "
          f"{len(jobs_of(items))} jobs; eligible {elig}; smoke {int(a.smoke)}")
    if bad:
        raise SystemExit("SELF-CHECK FAIL:\n  " + "\n  ".join(bad))
    print("[self-check] SELF-CHECK PASS: offsets, rows, every per-pool rate, the rules, the verdict statistics, the "
          "GO map, the gate files and the table reproduced")


