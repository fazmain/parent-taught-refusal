def restore_record(a, src: str, rc: dict | None = None) -> dict | None:
    """The restore base an arm was trained on, as the simulator arm must rebuild it: rank, the doc, the factor file
    and the hashes the load must reproduce. None for the arms trained on plain NORA."""
    rank = (rc or SOURCES[src])["restore"]
    if not rank:
        return None
    doc_path = Path({32: a.restore32, 128: a.restore128}[int(rank)])
    doc = load_json(doc_path)
    if int(doc["rank"]) != int(rank):
        raise SystemExit(f"{doc_path} is a rank-{doc['rank']} restore; {src} was trained on rank {rank}")
    return {"rank": int(rank), "doc": str(doc_path), "factors": doc["factors"],
            "factors_sha1": doc["factors_sha1"], "factors_bytes": int(doc["factors_bytes"]),
            "checkpoint": doc["checkpoint"], "emb_rows": int(doc["emb_rows"]),
            "fingerprint_base": doc["fingerprint_base"]["all"], "fingerprint_after": doc["fingerprint_after"]["all"],
            "addon_mb": float(doc["addon_mb"])}


RECIPE_KEYS = ("name", "rows", "align_weight", "align_ref", "restore", "text", "lora_args")


CALIB_SOURCE = "experiments/g16_install.py stage 0 (pod 16), calib_g16.json"


def write_gate(a, src: str, offsets: dict, summ: dict, steps: int, calib_sha: str, rc: dict | None = None,
               exp: str = EXP, calib_source: str | None = None, offset: str = RULE_OFFSET,
               arm: str | None = None) -> Path:
    """The small json the simulator arm is driven by: which adapter, which restore base (with the hashes the load
    must reproduce), which b, and where that b comes from. `rc` (default the round-4 recipe of `src`) is the recipe the
    simulator re-checks the adapter's train_meta against, so a round-5 arm carries its own LoRA arguments.

    `offset` / `arm` are round 6's hooks: the calibration ablation needs the SAME adapter at the argmax (offset "b0",
    which writes b = 0.0 and quantile null - that pair IS the label - under a name of its own) beside its b95
    gate. At the default b95 the file written is byte for byte the round-4 / round-5 one."""
    key = key_of(src, offset)
    arm = arm or arm_name(src, offset)
    s = summ[key]
    o = offsets[src]
    rc = rc or SOURCES[src]
    doc = {"exp": exp, "ts": time.strftime("%Y-%m-%d %H:%M:%S"), "arm": arm, "source": src,
           "adapter": str(Path(a.adapters) / rc["name"]), "adapter_name": rc["name"],
           "recipe": {k: rc[k] for k in RECIPE_KEYS if k in rc},
           "steps": int(steps), "checkpoint": a.checkpoint, "suite": a.suite, "time_horizon": int(a.time_horizon),
           "restore": restore_record(a, src, rc),
           "b": float(o[offset]), "quantile": OFFSET_Q[offset],
           "calibration": {"file": str(a.calib), "sha256": calib_sha, "n_b": o["n_b"], "n_open": o["n_open"],
                           "n": o["n"], "b_set": o["b_set"], "b90_stored": o["b90_stored"],
                           "b90_recomputed": o["b90_check"], "b97": o["b97"],
                           "stop_rate_b95": o["stop_rate_b95"], "train_overlap": o["train_overlap"],
                           "source": calib_source or CALIB_SOURCE},
           "verdict_ids": {k: list(v) for k, v in VERDICT_IDS_REF.items()},
           "n_text_per_call": len(VERDICT_IDS_REF[STOP]),
           "fresh": {"set": CONFIRM, "sha256": CONFIRM_SHA256,
                     "hold": {p: s["pools"].get(p, {}).get("hold") for p in POOLS},
                     "rules_pass": s["rules_pass"]}}
    p = gate_path(a.out, arm)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(doc, indent=1, default=float))
    return p


