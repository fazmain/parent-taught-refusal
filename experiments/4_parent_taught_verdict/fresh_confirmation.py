def offsets_from_calib(calib: dict, sources=None) -> dict:
    """b_95 / b_97 (and b_0) per verdict source from round 3's stored calibration differences, with round 3's own b_90
    recomputed the same way and asserted equal to the b it stored: the frozen model's per-call decision logit d is
    fixed, so every offset is a quantile of the SAME 212 non-training calibration prefills. `sources` (default the
    round-4 arms) lets round 5 read a calibration file fitted by the same rule on its own arms."""
    out, bad = {}, []
    for src in (sources or PRIORITY):
        c = calib.get(src)
        if c is None:
            bad.append(f"{src}: no calibration record in the G16 file")
            continue
        d = np.asarray(c["d"], dtype=np.float64)
        m = np.asarray(c["in_b"], dtype=bool)
        if len(d) != int(c["n_open"]) or int(m.sum()) != int(c["n_b"]):
            bad.append(f"{src}: {len(d)} decision logits / {int(m.sum())} in the b set, stored "
                       f"{c['n_open']} / {c['n_b']}")
            continue
        if float(c["quantile"]) != CHECK_Q:
            bad.append(f"{src}: stored quantile {c['quantile']} != G16's {CHECK_Q}")
            continue
        b90 = -float(np.quantile(d[m], CHECK_Q))
        if b90 != float(c["b"]):
            bad.append(f"{src}: b_90 recomputed {b90:+.6f} != the stored b {float(c['b']):+.6f}")
            continue
        rec = {"b0": 0.0, "b90_check": b90, "b90_stored": float(c["b"]), "n_b": int(c["n_b"]),
               "n_open": int(c["n_open"]), "n": int(c["n"]), "b_set": c["b_set"],
               "train_overlap": c["train_overlap"]}
        for name, q in OFFSET_Q.items():
            if q is None:
                continue
            rec[name] = -float(np.quantile(d[m], q))
            rec[f"stop_rate_{name}"] = float((d[m] + rec[name] > 0).mean())
        out[src] = rec
    if bad:
        raise SystemExit("the stored G16 calibration does not reproduce its own offsets:\n  " + "\n  ".join(bad))
    return out


def b_of(offsets: dict, src: str, offset: str):
    return None if offset == "none" else float(offsets[src][offset])


# --------------------------------------------------------------------------------- generation

def run_jobs(src: str, offset: str, b, policy, jobs: list, eval_frames: Path, fh, proc: VerdictOffset | None,
             cache: dict) -> int:
    """One generation per (sentence, frame) job at one offset; with an offset, the processor's record travels
    into the row so the self-check can re-derive the decision from d + b."""
    t0 = time.time()
    for it, init in jobs:
        frame = f"t{it['task_id']}_i{init}.png"
        if frame not in cache:
            cache[frame] = load_png(Path(eval_frames) / frame)
        r = policy.act(cache[frame], it["text"])
        gen = [int(t) for t in r["gen_ids"]]
        e = proc.log[-1] if proc is not None else {}
        row = {"model": src, "offset": offset, "b": None if b is None else float(b), "pool": it["pool"],
               "idx": it["idx"], "id": it["id"], "harm": it["harm"], "text_sha1": it["text_sha1"],
               "task_id": it["task_id"], "init": init, "frame": frame, "cls": classify(r),
               "verdict": parse_verdict(gen, VERDICT_IDS_REF), "n_text": int(r["n_text"]),
               "invalid": bool(r["invalid"]), "gen_ids": gen, "first": e.get("first"), "d": e.get("d"),
               "top2": e.get("top2"), "raw": e.get("raw"), "chosen": e.get("chosen")}
        fh.write(json.dumps(row) + "\n")
        fh.flush()
    print(f"[{key_of(src, offset)}] {len(jobs)} generations in {time.time() - t0:.0f}s", flush=True)
    return len(jobs)


def run_fresh(a, items: list[dict], offsets: dict, factory, check_ids, stop_go, P: dict | None = None,
              plan=None) -> None:
    """One checkpoint load per source; the verdict sources run their three offsets behind the same load.

    `P` (a paths dict with dir / rows) and `plan` ([(source, offsets)] in load order; a source whose offsets are
    ("none",) is a free arm and gets no offset processor) are round 5's hooks: the same loop over its own arms and its
    own two offsets."""
    P = P or paths(a.out)
    plan = plan or [(s, OFFSETS if is_verdict(s) else ("none",)) for s, o in models_of() if o in ("b0", "none")]
    P["dir"].mkdir(parents=True, exist_ok=True)
    jobs = jobs_of(items)
    done = {(r["model"], r["offset"], r["idx"], r["init"]) for r in read_jsonl(P["rows"])}
    if done:
        print(f"[resume] {len(done)} generations already in {P['rows']}", flush=True)
    checked = False
    with P["rows"].open("a") as fh:
        for src, offs in plan:
            todo = {o: [j for j in jobs if (src, o, j[0]["idx"], j[1]) not in done] for o in offs}
            if not any(todo.values()):
                print(f"[{src}] every generation present; skipped", flush=True)
                continue
            policy = factory(src)
            if not checked:
                check_ids(policy)
                checked = True
            cache: dict = {}
            if tuple(offs) != ("none",):
                proc = VerdictOffset(*stop_go)
                remove = install_offset(policy, proc)
                for o in offs:
                    if todo[o]:
                        proc.b = float(offsets[src][o])
                        run_jobs(src, o, proc.b, policy, todo[o], Path(a.eval_frames), fh, proc, cache)
                remove()
            elif todo["none"]:
                run_jobs(src, "none", None, policy, todo["none"], Path(a.eval_frames), fh, None, cache)
            del policy
            free_cuda()


