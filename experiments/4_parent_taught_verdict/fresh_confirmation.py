class _Tok:
    """The verdict half of NORA's tokenizer, enough for `build_training_rows.verdict_token_ids`."""

    def __call__(self, text, add_special_tokens=False):
        return {"input_ids": list(VERDICT_IDS_REF[text])}

    def convert_ids_to_tokens(self, ids):
        return [str(i) for i in ids]

    def decode(self, ids):
        return {tuple(v): k for k, v in VERDICT_IDS_REF.items()}[tuple(ids)]


def _test_arm(tmp: Path, doc: dict) -> None:
    """eval_in_simulator's `VerdictArm`: the load order (adapter checked against the recipe, then the offset installed inside the
    policy's own generate), the restore context read from the doc the gate records, and the per-episode verdict
    accounting read back from the `.gen.jsonl` sidecar."""
