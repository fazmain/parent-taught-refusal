    assert s["verdict_b"] == arm.b and s["verdict_arm"] == doc["arm"] and s["verdict_restore_rank"] is None
    side.write_text(side.read_text() + json.dumps({"gen_ids": [9, 9], "n_text": 2, "invalid": False}) + "\n")
    s2 = arm.summary(vid, {"invalid_decodes": 0})
