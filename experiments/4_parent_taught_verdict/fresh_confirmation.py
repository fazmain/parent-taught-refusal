    print(f"[self-test] VerdictArm: the adapter is checked against the recipe the gate records and merged by "
          f"g15_install.load_arm, then the offset b = {arm.b:+.2f} is installed inside the policy's own generate "
          f"(a benign [GO] at d = -1.0 becomes [STOP]); the episode row counts 3 verdict text tokens per call, 0 "
          f"invalid, 0 leaks, and a 2-token generation is counted as a leak")


