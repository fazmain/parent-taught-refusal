        s = summ[key_of(src, offset)]
        text = SOURCES[src]["text"] if src != BASE else "NORA libero-goal, no adapter"
        b = "" if s["b"] is None else f"{s['b']:+.3f}"
        vals = "".join(f"{s['pools'].get(p, {}).get('hold', float('nan')):20.3f}" for p in POOLS)
