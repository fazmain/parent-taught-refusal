def _plan_parity() -> None:
    """The installed verdict model plans exactly the (test, pool, prompt, init, swap) episodes the
    parent-gated reference's parent_judge arm ran (the selection set), and adding it leaves every arm's plan of that
    run unchanged."""
    import eval_in_simulator as F
    ref, pools, demo, tasks, twins = _selection_inputs()
    task_of_map = {}
    for r in ref:
        task_of_map.setdefault(r["prompt"], (int(r["task_id"]), r["match_score"]))

    def task_of(p):
        if p not in task_of_map:
            raise AssertionError("a planned prompt never ran on pod 8b")
        ti, ms = task_of_map[p]
        return ti, (1.0 if ms is None else float(ms))

    keys = ("test", "pool", "idx", "init", "prompt", "task_id", "category", "tag")

    def key(it, arm):
        return tuple(it.get(k) for k in keys) + (arm, it.get("swap_instruction"), it.get("twin_id"))

    modes8 = ["parent_judge", "parent_read", "parent_only", "random_dir", "oracle", "always_go"]
    plan8 = F.build_plan(pools, demo, twins, tasks, task_of, ["g1", "free_lora_300"], gate_modes=modes8)
    assert {it["uid"] for it in plan8} == {r["uid"] for r in ref} and len(plan8) == len(ref) == 1044
    plan_all = F.build_plan(pools, demo, twins, tasks, task_of, ["g1", "free_lora_300", F.VERDICT_MODEL],
                            gate_modes=modes8)
    others = [it for it in plan_all if it["model"] != F.VERDICT_MODEL]
    assert [it["uid"] for it in others] == [it["uid"] for it in plan8], "the verdict arm changed another model"
    plan = F.build_plan(pools, demo, twins, tasks, task_of, [F.VERDICT_MODEL], gate_modes=[])
    pj = [r for r in ref if r["model"] == "g1" and r.get("gate_mode") == "parent_judge"]
    want = Counter(key(r, r["arm"].replace("parent_judge", "", 1).lstrip("_")) for r in pj)
    got = Counter(key(it, it["arm"].replace("none", "", 1)) for it in plan)
    assert got == want, f"the verdict plan differs from the pod-8b parent_judge rows: {len(got)} vs {len(want)}"
    per_test = Counter(it["test"] for it in plan)
    assert dict(per_test) == {"gate": 50, "nonattempt": 96, "twins": 60, "overrefusal_para": 80, "abort": 24}, per_test
    assert len(plan) == 310 and {it["model"] for it in plan} == {F.VERDICT_MODEL}
    assert all(it["gate_mode"] is None for it in plan) and all(it["arm"] == "none" or it["arm"].startswith("swap_")
                                                               for it in plan)
    assert all(F.split_arm(F.VERDICT_MODEL, it["arm"]) == (None, it["arm"]) for it in plan)
    lab = {it["harm_label"] for it in plan if it["test"] == "twins" and it["pool"] == "twins_benign"}
    assert lab == {False}, lab
    print(f"[self-test] plan parity: {F.VERDICT_MODEL} plans {len(plan)} episodes = the {len(pj)} pod-8b "
          f"parent_judge rows (test, pool, idx, init, prompt, task, swap): "
          + ", ".join(f"{t} {n}" for t, n in per_test.items())
          + f"; the {len(plan8)} pod-8b uids unchanged when it is added; smoke plan "
          f"{len(F.smoke_plan(plan))} episodes")
    print("[self-test] plan table (the new arm alone):\n" + "\n".join("    " + l for l in F.plan_table(plan)))


