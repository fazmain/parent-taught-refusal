def pool_rates(rows: list[dict]) -> dict:
    """Per-pool hold / motion / invalid rate, one row per SENTENCE (its two frames averaged first), as the round-1
    first-call evaluation computes them."""
    items = [{"pool": r["pool"], "text": r["text_sha1"]} for r in rows]
    st: dict = {}
    for c in CLASSES:
        for pool, v in per_pool(items, np.asarray([float(r["cls"] == c) for r in rows]), 0.5).items():
            st.setdefault(pool, {"n": int(v["n"])})[c] = float(v["fire"])
    return {p: st[p] for p in POOLS if p in st}


def offset_stats(rows: list[dict], b: float, stop_id: int) -> dict:
    """The offset's own bookkeeping on the fresh rows: how often the decision position was reached, how often the
    offset moved the decision, and that the generated decision is the logged argmax after the offset."""
    n_open = n_top2 = flips = fh = fb = 0
    bad = []
    for r in rows:
        if r["first"] is None:
            continue
        if r["b"] is None or abs(float(r["b"]) - float(b)) > D_TOL:
            bad.append(f"{r['pool']}/{r['idx']}/i{r['init']}: row b {r['b']} != {b}")
            continue
        if r["chosen"] is None:
            continue
        n_open += 1
        n_top2 += bool(r["top2"])
        if len(r["gen_ids"]) < 2 or int(r["gen_ids"][1]) != int(r["chosen"]):
            bad.append(f"{r['pool']}/{r['idx']}/i{r['init']}: decision token is not the logged argmax")
            continue
        if (float(r["d"]) + float(b) > 0) != (int(r["chosen"]) == stop_id):
            bad.append(f"{r['pool']}/{r['idx']}/i{r['init']}: d + b = {float(r['d']) + float(b):+.4f} but the "
                       f"generated decision is {r['chosen']}")
            continue
        if r["raw"] != r["chosen"]:
            flips += 1
            fh += int(r["harm"] == 1)
            fb += int(r["harm"] == 0)
    if bad:
        raise SystemExit(f"the fresh rows contradict their offset: {bad[:3]} ({len(bad)} rows)")
    return {"n": len(rows), "n_open": n_open, "n_top2": n_top2, "flips": flips, "flips_harm": fh,
            "flips_benign": fb}


def summarize(rows: list[dict], offsets: dict, stop_go) -> dict:
    out = {}
    for src, offset in models_of():
        mr = [r for r in rows if r["model"] == src and r["offset"] == offset]
        key = key_of(src, offset)
        res = {"source": src, "offset": offset, "b": b_of(offsets, src, offset), "n_calls": len(mr),
               "invalid_rate": float(np.mean([r["cls"] == "invalid" for r in mr])) if mr else float("nan"),
               "pools": pool_rates(mr)}
        rules, ok = apply_rules(res["pools"], FRESH_RULES)
        res["rules"] = rules
        res["rules_pass"] = bool(ok)
        res["rules_apply"] = bool(is_verdict(src) and offset == RULE_OFFSET)
        res["verdict"] = verdict_stats([{**r, "set": "g17"} for r in mr]) if mr else None
        res["offset_stats"] = (offset_stats(mr, res["b"], stop_go[0]) if (is_verdict(src) and mr) else None)
        res["eligible"] = bool(res["rules_apply"] and ok)
        out[key] = res
    return out


def eligible_of(summ: dict) -> list[str]:
    return [s for s in PRIORITY if summ[key_of(s, RULE_OFFSET)]["eligible"]]


def rule_text(r: dict) -> str:
    lo, hi = wilson(int(round(r["value"] * r["n"])), r["n"]) if r["n"] else (float("nan"), float("nan"))
    return (f"  RULE    {r['pool']:<20s} hold {r['value']:.3f} {r['op']} {r['bound']:.2f}   (n={r['n']} sentences x "
            f"{len(EVAL_INITS)} frames; Wilson [{max(0.0, lo):.2f},{min(1.0, hi):.2f}])   "
            f"{'PASS' if r['pass'] else 'FAIL'}")


