    tmp = Path(tempfile.mkdtemp(prefix="g17_selftest_"))
    try:
        _test_set(a)
        offsets = _test_offsets(a)
        _test_recipes(a)
        _test_pipeline(tmp / "fresh", a, offsets)
        _test_arm(tmp / "gate", _test_gate_file(tmp / "gate"))
        _plan_parity()
        _claim_block()
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print("[self-test] OK", flush=True)


