def load_confirm(path) -> list[dict]:
    """The fresh set, its sha256 asserted against the pre-registration (the file was written before any number)."""
    p = Path(path)
    raw = p.read_bytes()
    got = hashlib.sha256(raw).hexdigest()
    if got != CONFIRM_SHA256:
        raise SystemExit(f"{p} sha256 {got} != the pre-registered {CONFIRM_SHA256}")
    return [json.loads(l) for l in raw.decode("utf-8").splitlines() if l.strip()]


def build_items(confirm, f1_data: Path, smoke: bool) -> list[dict]:
    """The 87 fresh sentences with their scene (nearest trained task, as the G11 scoring and round 3 assign it)."""
    from build_free_install_data import LIBERO_GOAL_TASKS
    pools = load_json(Path(f1_data) / "pools.json")
    tasks = list(pools["meta"]["tasks"])
    if tasks != LIBERO_GOAL_TASKS:
        raise SystemExit("pools.json meta.tasks is not the recorded libero_goal order")
    rows = load_confirm(confirm)
    items = [{"idx": i, "id": r["id"], "pool": r["pool"], "harm": int(r["harm"]), "text": r["text"],
              "category": r.get("category", ""), "task_id": None} for i, r in enumerate(rows)]
    bad = [it["pool"] for it in items if it["pool"] not in POOLS]
    if bad:
        raise SystemExit(f"{len(bad)} sentences carry a pool outside {list(POOLS)}, e.g. {bad[0]}")
    counts = dict(Counter(it["pool"] for it in items))
    if counts != FULL_COUNTS:
        raise SystemExit(f"fresh pool counts {counts} != the pre-registered {FULL_COUNTS}")
    assign_scenes(items, tasks)
    for it in items:
        it["text_sha1"] = sha(it["text"])
    if smoke:
        seen, keep = Counter(), []
        for it in items:
            if seen[it["pool"]] < SMOKE_PER_POOL:
                seen[it["pool"]] += 1
                keep.append(it)
        items = keep
    return items


def jobs_of(items: list[dict]) -> list[tuple[dict, int]]:
    return [(it, init) for it in items for init in EVAL_INITS]


